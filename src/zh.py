#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
中文繁简归一化 —— 一个容易被忽视、但会在中文检索里致命的前置步骤

问题（2026-09-19 实测，不是理论推演）
--------------------------------------
本项目语料是中文维基百科，**繁简混排**（不同条目由不同地区的编者创建）：
「蘇花古道」条目名是繁体，「张克忠」条目名是简体。

同一个问题，只改字形，结果天差地别：

    query「张克忠的籍贯是哪里」（简体）→ BM25 #1 = 张克忠     ✅ 答案「天津」
    query「張克忠的籍貫是哪裡」（繁体）→ BM25 #1 = 哈辛·耶巴達 ❌ 检索失败 → 模型拒答

四个字不同，一个答对一个答不出。失败原因有两层：

  1. **字面层**：繁体「張克忠」在简体索引里根本查不到，df=0，这个词等于不存在。
  2. **分词层**（更隐蔽）：jieba 的词典以简体为主，繁体串会被切碎成单字。
     而单字在第 8 步就被 `_keep` 过滤掉了（那是正确的决定：单字全是噪声）。
     → 结果：query 里唯一有信息量的词，**在进入检索之前就消失了**。
     就算把「張」加进 jieba 词典，只要它被切成单字，照样被丢。

解法：**建索引和查询都先归一化到同一形态**（这里统一到简体）。
    「張克忠」→「张克忠」→ 索引里的「张克忠」→ 命中。

⚠️ 两条铁律
------------
 1. **两边都要转，且必须调用同一个函数**。
    只转一边 = 换了一种字形的字面不匹配，比不转更糟（而且静默查不到，不报错）。
    所以本文件的 `norm_text` 是唯一入口，`build_bm25.py` 和 `search_bm25.py` 都 import 它。
    （这正是第 8 步 §5.4「检测口径必须 == 修复口径」的同一条纪律。）

 2. **索引的归一化状态要写进 meta，查询时校验**。
    否则「新代码 + 旧索引」或「旧代码 + 新索引」都能跑起来，
    表现是"某些词永远搜不到"，却没有任何报错。

为什么不统一到繁体：jieba 词典和本机大部分工具链都以简体为主，转简体的分词质量更稳。
语料侧只要建索引时转过一次，检索侧就永远匹配得上。
"""

TARGET = "zh-cn"          # 统一形态：简体

try:
    from zhconv import convert as _zh_convert
    HAVE_ZHCONV = True
except Exception:         # pragma: no cover
    _zh_convert = None
    HAVE_ZHCONV = False

_warned = False


def norm_text(s: str) -> str:
    """
    把繁简混排文本归一化到统一形态。

    没装 zhconv 时**原样返回**并警告一次 —— 这不是静默降级：
    索引端和查询端调的是同一个函数，两边行为一致，所以检索依然自洽，
    只是繁体 query 会漏（这个损失会在日志里明确说出来）。
    """
    global _warned
    if not s:
        return s or ""
    if not HAVE_ZHCONV:
        if not _warned:
            import sys
            print("[警告] 未安装 zhconv —— 繁简归一化已跳过。"
                  "繁体查询词会检索失败（简体查询不受影响）。"
                  "安装：pip install zhconv", file=sys.stderr)
            _warned = True
        return s
    return _zh_convert(s, TARGET)


def fan_ratio(s: str) -> float:
    """
    粗略估计文本的「繁体程度」：0.0 = 全简体，越接近 1 越繁。

    做法很取巧 —— **把转换器反过来当检测器用**：
    对同一串做繁体→简体转换，数有多少个字变了，变了的就是繁体字。
    好处是不用维护任何字表（zhconv 的映射表就是最全的字表），
    也不会漏掉生僻繁体字。

    ⚠️ 只在「繁→简」方向有效：简体文本转换后不变，所以返回 0；
      反之不能用来检测简体。本项目只需要判繁体，够用。
    ⚠️ 长度变化时（转换可能增删字符）返回 0 —— 宁可不判，也不要算错。
    """
    if not s:
        return 0.0
    n = norm_text(s)
    if len(n) != len(s):
        return 0.0
    diff = sum(1 for a, b in zip(s, n) if a != b)
    return diff / len(s)


def looks_fanti(s: str, thresh: float = 0.02) -> bool:
    """
    是否含「足够多」的繁体字。默认阈值 2% —— 一个 200 字的段落里
    有 4 个字是繁体就算。定得很低是因为：只要 query 里出现一个繁体词
    （如「張克忠」里的「張」），在强制简体的索引里就已经查不到了。
    """
    return fan_ratio(s) >= thresh
